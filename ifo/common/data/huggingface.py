class MaskedDistractingControlSuiteDataset(DeepMindControlSuiteDataset):
    """
   This dataset contains expert trajectories generated by a Proximal Policy Optimization (PPO)
   reinforcement learning agent trained on 4 environments of the Distracting Control Suite.
   For each environment we collect data with different levels of distraction, which we define below,
   and masks for the agent.

    Levels of Distraction:
        None: Vanilla DeepMind Control Suite without visual distractions. The environment uses
              the default static background and maintains a fixed camera position.

        Low: Dynamic background distractors only.
             - Background: Video frames from the DAVIS dataset are played sequentially. At each
               step, the background advances to the next frame, cycling through the video
               (direction reverses at endpoints).
             - Camera: Dynamic during an episode, changes position, rotation, and zoom, with distractor magnitude 0.1

        Hard: Both distraction types combined:
             - Background: Same dynamic video background as "Low" level.
             - Camera: Dynamic during an episode, changes position, rotation, and zoom, with distractor magnitude 0.3


    Data Fields:
    - observation: The current RGB observation from the environment.
    - mask: A segmentation mask of the agent, with everything zero, except the agent, which is 255.
    - action: The action predicted by the agent for the current observation.
    - state: The current state of the environment.
    - reward: The received reward for the current observation.
    - terminated: If the episode has terminated with the current observation.
    - truncated: If the episode is truncated with the current observation.

    Available Environments:
        - cheetah_run
        - cheetah_run_distractor_low
        - cheetah_run_distractor_hard

        - hopper_hop
        - hopper_hop_distractor_low
        - hopper_hop_distractor_hard

        - humanoid_walk
        - humanoid_walk_distractor_low
        - humanoid_walk_distractor_hard

        - walker_run
        - walker_run_distractor_low
        - walker_run_distractor_hard

    Data Splits:
        - train: 9,000,000 steps (90%)
        - test: 1,000,000 steps (10%)
    """

    def __init__(
        self,
        path: str = "EpicPinkPenguin/visual_distracting_control_suite",
        name: Optional[str] = None,
        split: str = "train",
        cache_dir: Optional[str] = None,
        num_proc: Optional[int] = None,
        block_size: Optional[int] = None,
        columns: Optional[List[str]] = None,
        transform: Optional[DictTransform] = None,
        use_sam_mask: bool = False,
        **kwargs,
    ) -> None:
        """
        Initialize DeepMindControlSuiteDataset.

        Args:
            path (str, optional): Path or name of the dataset. Defaults to "EpicPinkPenguin/visual_distracting_control_suite".
            name (str, optional): Defining the name of the dataset configuration (e.g., "acrobot_swingup").
            split (str, optional): Split of the dataset to load. Defaults to "train".
            cache_dir (str, optional): Directory to read/write data.
            num_proc (int, optional): Number of processes to use.
            block_size (int, optional): Block size of the data.
                Data gets an additional temporal dimension if not 1.
            columns (List[str], optional): Columns to load. If None, all columns are loaded.
            transform (Callable, optional): Transform to apply. Requires DictTransform.
            use_sam_mask (bool, optional): If True, use the SAM mask instead of the ground truth mask. Defaults to False.
            **kwargs: Additional keyword arguments passed to `load_dataset`.
        """

        super().__init__(
            path=path,
            name=name,
            split=split,
            cache_dir=cache_dir,
            num_proc=num_proc,
            block_size=block_size,
            columns=columns,
            transform=transform,
            **kwargs,
        )

        assert "mask" in self.data.column_names, (
            "SegmentationDataset requires a 'mask' column, "
            f"but got {self.data.column_names}"
        )

        if use_sam_mask:
            self.data = self.data.remove_columns("mask")
            self.data = self.data.rename_column("pred_mask", "mask")
            # Re-apply the torch format after column operations: HuggingFace caches the column
            # mapping internally, so without this the renamed column won't be found at access time.
            self.data = self.data.with_format("torch", columns=self.columns)


class MetaWorldDataset(HuggingFaceDataset):
    """
    A dataset containing expert trajectories for Meta-World, a benchmark for
    meta-reinforcement learning and multi-task learning consisting of 4 distinct
    robotic manipulation tasks. The trajectories were generated using the built-in
    scripted policies (experts) provided by the benchmark.

    Levels of Distraction:
        Dynamic background distractors only.
            - Background: Video frames from the DAVIS dataset are played sequentially. At each
              step, the background advances to the next frame, cycling through the video
              (direction reverses at endpoints).
            - Camera: Not dynamic during an episode, fixed position with no scale or rotation changes.

    Data Fields:
    - observation: The current RGB observation from the environment.
    - mask: A segmentation mask of the agent, with everything zero, except the agent, which is 255.
    - action: The action predicted by the agent for the current observation.
    - state: The current state of the environment.
    - reward: The received reward for the current observation.
    - terminated: If the episode has terminated with the current observation.
    - truncated: If the episode is truncated with the current observation.

    Data Splits:
        - train: 1,000,000 steps (91%)
        - test: 100,000 steps (9%)

    Note:
        If ``name`` contains ``\"distracting\"`` or ``\"masked\"`` and an
        ``observation_distracted`` column is present, this column is used as the
        ``observation`` field (replacing the original ``observation`` column).
    """

    def __init__(
        self,
        path: str = "EpicPinkPenguin/visual_distracting_metaworld",
        name: Optional[str] = None,
        split: str = "train",
        cache_dir: Optional[str] = None,
        num_proc: Optional[int] = None,
        block_size: Optional[int] = None,
        columns: Optional[List[str]] = None,
        transform: Optional[DictTransform] = None,
        use_distracted_obs: bool = False,
        use_sam_mask: bool = False,
        **kwargs,
    ) -> None:
        """
        Initialize DistractingMetaWorldDataset.

        Args:
            path (str, optional): Path or name of the dataset. Defaults to "EpicPinkPenguin/visual_distracting_metaworld".
            name (str, optional): Defining the name of the dataset configuration (e.g., "hammer-v3").
                Must be the bare HuggingFace config name (e.g. "basketball-v3"), without any
                ``"masked-"`` or ``"distracting-"`` prefix, since those don't exist on HuggingFace.
            split (str, optional): Split of the dataset to load. Defaults to "train".
            cache_dir (str, optional): Directory to read/write data.
            num_proc (int, optional): Number of processes to use.
            block_size (int, optional): Block size of the data.
                Data gets an additional temporal dimension if not 1.
            columns (List[str], optional): Columns to load. If None, all columns are loaded.
            transform (Callable, optional): Transform to apply. Requires DictTransform.
            use_distracted_obs (bool, optional): If True, the ``observation_distracted`` column
                replaces the vanilla ``observation`` column. Set this when loading data for a
                ``distracting`` or ``masked`` environment variant. Defaults to False.
            use_sam_mask (bool, optional): If True, use the SAM mask instead of the ground truth mask. Defaults to False.
            **kwargs: Additional keyword arguments passed to `load_dataset`.
        """

        super().__init__(
            path=path,
            name=name,
            split=split,
            cache_dir=cache_dir,
            num_proc=num_proc,
            block_size=block_size,
            columns=columns,
            transform=transform,
            **kwargs,
        )

        assert "mask" in self.data.column_names, (
            "SegmentationDataset requires a 'mask' column, "
            f"but got {self.data.column_names}"
        )

        # Rename observation_distracted -> observation when using a distracting/masked variant.
        # NOTE: `name` is always the bare HF config name (no "masked-"/"distracting-" prefix),
        # so we rely on the explicit `use_distracted_obs` flag instead of inspecting `name`.
        if use_distracted_obs and "observation_distracted" in self.data.column_names:
            self.data = self.data.remove_columns("observation")
            self.data = self.data.rename_column("observation_distracted", "observation")
            # Re-apply the torch format after column operations: HuggingFace caches the column
            # mapping internally, so without this the renamed column won't be found at access time.
            self.data = self.data.with_format("torch", columns=self.columns)

        if use_sam_mask:
            self.data = self.data.remove_columns("mask")
            mask_name = "pred_mask_distracted" if use_distracted_obs else "pred_mask"
            self.data = self.data.rename_column(mask_name, "mask")
            # Re-apply the torch format after column operations: HuggingFace caches the column
            # mapping internally, so without this the renamed column won't be found at access time.
            self.data = self.data.with_format("torch", columns=self.columns)
